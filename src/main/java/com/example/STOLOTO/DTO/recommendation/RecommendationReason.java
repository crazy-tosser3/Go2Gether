package com.example.STOLOTO.DTO.recommendation;

/** Почему событие попало в рекомендации. Фронт показывает подпись по коду. */
public enum RecommendationReason {
    /** Вид спорта из интересов профиля. */
    INTEREST,
    /** Пользователь уже ходил на этот вид спорта. */
    PLAYED_BEFORE,
    /** Тот же город, что в профиле или в истории. */
    SAME_CITY,
    /** Рядом с переданными координатами. */
    NEARBY,
    /** Уровень совпадает с уровнем пользователя. */
    LEVEL_MATCH,
    /** Записались люди, с которыми пользователь уже играл. */
    FRIENDS_GOING,
    /** Организатор, у которого пользователь уже был. */
    FAMILIAR_ORGANIZER,
    /** Много записавшихся. */
    POPULAR,
    /** Скоро начнётся. */
    SOON,
    /** Похожее событие: тот же вид спорта. */
    SAME_SPORT,
    /** Похожее событие: та же категория спорта. */
    SAME_CATEGORY,
    /** Похожее событие: тот же организатор. */
    SAME_ORGANIZER,
    /** Похожее событие: пересекается состав участников. */
    SHARED_PARTICIPANTS
}
